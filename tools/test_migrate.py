"""Run: python3 -I -m unittest discover -s tools -p 'test_*.py'"""
import json
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import migrate_kaleidoscope as m  # noqa: E402

SOURCE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "kaleidoscope.json")


class MigrateTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        with open(SOURCE, encoding="utf-8") as f:
            cls.source = json.load(f)
        cls.out = m.migrate(cls.source)
        cls.achievements = cls.out["achievements"]

    def test_tab_comes_from_root(self):
        tab = self.out["tab"]
        self.assertEqual(tab["id"], "cooking")
        self.assertEqual(tab["title"], "森罗厨房")
        self.assertEqual(tab["icon"], {"item": "kaleidoscopecookery:pot"})

    def test_counts(self):
        self.assertEqual(len(self.achievements), 33)
        for nitrogen in ("nitrogen_100", "nitrogen_300", "nitrogen_1000", "nitrogen_3000", "root"):
            self.assertNotIn(nitrogen, self.achievements)

    def test_parents_preserved_and_root_children_hang_on_tab(self):
        by_id = {a["id"]: a for a in self.source["advancements"]}
        for aid, ach in self.achievements.items():
            parent = by_id[aid]["parent"]
            if parent == "root":
                self.assertNotIn("parent", ach, aid)
            else:
                self.assertEqual(ach["parent"], parent, aid)

    def test_display_copied(self):
        source = {a["id"]: a for a in self.source["advancements"]}["burn_hand"]
        ach = self.achievements["burn_hand"]
        self.assertEqual(ach["title"], source["title"])
        self.assertEqual(ach["description"], source["description"])
        self.assertEqual(ach["icon"], {"item": source["icon"]})

    def test_event_criterion(self):
        ach = self.achievements["add_broth"]
        self.assertEqual(ach["trigger"], "cooking_action")
        self.assertEqual(ach["filter"], {"action": "put_soup_base_in_stockpot"})

    def test_kill_criterion(self):
        ach = self.achievements["oil"]
        self.assertEqual(ach["trigger"], "item_kill")
        self.assertIn("kaleidoscopecookery:iron_kitchen_knife", ach["filter"]["weapon"])

    def test_single_group_inventory_is_any_of(self):
        ach = self.achievements["dark_cuisine"]
        self.assertEqual(ach["trigger"], "item_obtain")
        self.assertNotIn("count", ach)
        self.assertEqual(sorted(ach["filter"]["item"]),
                         ["kaleidoscopecookery:dark_cuisine", "kaleidoscopecookery:suspicious_stir_fry"])

    def test_multi_group_inventory_is_grouped_unique(self):
        chili = self.achievements["dual_chili"]
        self.assertEqual(chili["count"], "unique")
        self.assertEqual(chili["unique-by"], "item")
        self.assertEqual(chili["goal"], 2)
        self.assertEqual(len(chili["unique-groups"]), 2)
        farmer = self.achievements["farmer_set"]
        self.assertEqual(farmer["goal"], 4)
        hats = [g for g in farmer["unique-groups"].values() if "kaleidoscopecookery:straw_hat" in g][0]
        self.assertEqual(sorted(hats), ["kaleidoscopecookery:straw_hat", "kaleidoscopecookery:straw_hat_flower"])
        self.assertEqual(sorted(farmer["filter"]["item"]), sorted(sum(farmer["unique-groups"].values(), [])))

    def test_items_renamed_by_the_port_are_mapped(self):
        text = m.dump(self.out)
        for missing in ("kaleidoscopecookery:tomato_seed", "kaleidoscopecookery:red_chili",
                        "kaleidoscopecookery:chili_seed", "kaleidoscopecookery:lettuce_seed",
                        "kaleidoscopecookery:tea_seed", '"kaleidoscopecookery:kitchen_shovel"'):
            self.assertNotIn(missing, text)
        seeds = self.achievements["tomato_seed"]
        self.assertEqual(seeds["icon"], {"item": "customcrops:tomato_seeds"})
        self.assertEqual(sorted(seeds["filter"]["item"]),
                         ["customcrops:lettuce_seeds", "customcrops:pepper_seeds", "customcrops:tomato_seeds",
                          "kaleidoscopecookery:wild_rice"])
        self.assertEqual(self.achievements["stir_fry"]["icon"], {"item": "kaleidoscopecookery:kitchen_shovel_no_oil"})
        chili = self.achievements["dual_chili"]["unique-groups"]
        self.assertIn(["customcrops:pepper"], chili.values())

    def test_dump_is_json_scalar_yaml(self):
        text = m.dump(self.out)
        self.assertTrue(text.startswith("# Generated by tools/migrate_kaleidoscope.py"))
        self.assertIn('  title: "森罗厨房"', text)
        self.assertIn('  add_broth:', text)


if __name__ == "__main__":
    unittest.main()
